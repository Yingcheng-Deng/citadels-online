export function buildLimit(id: number) { return id === 22 ? 0 : id === 7 ? 3 : [15,23].includes(id) ? 2 : 1; }
export function freeOfLimit(id: number, card: {key:string;color:string}) { return id !== 22 && (card.key === "stables" || (id === 21 && card.color === "trade")); }
